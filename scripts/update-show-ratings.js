/*
  Saves MLB The Show player ratings to data/show-ratings.js for the team pages.

  Run: node scripts/update-show-ratings.js
  Uses the game's public card list. Only Live Series cards are kept: those carry each player's
  current rating, which the game updates with every roster update during the season.
  Each new game year has its own site, so bump GAME_YEAR when The Show 27 comes out.
*/
const fs = require("fs");
const path = require("path");

const GAME_YEAR = 26;
const OUT_FILE = path.join(__dirname, "../data/show-ratings.js");

const sleep = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));

async function page(number) {
  const url = `https://mlb${GAME_YEAR}.theshow.com/apis/items.json?type=mlb_card&page=${number}`;
  const maxAttempts = 5;
  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    let retryAfter = 0;
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
      if (!response.ok) {
        const header = response.headers.get("retry-after");
        if (header) {
          const seconds = Number(header);
          retryAfter = Number.isFinite(seconds) ? seconds * 1000 : Date.parse(header) - Date.now();
        }
        await response.body?.cancel();
        const error = new Error(`HTTP ${response.status}`);
        error.status = response.status;
        error.permanent = ![408, 429].includes(response.status) && response.status < 500;
        throw error;
      }
      const result = await response.json();
      if (!Array.isArray(result.items) || !Number.isInteger(result.total_pages) || result.total_pages < 1) {
        throw new Error("Invalid card-list response (expected items and total_pages)");
      }
      return result;
    } catch (error) {
      const detail = [error.message, error.cause?.code].filter(Boolean).join(" / ");
      if (error.permanent || attempt === maxAttempts) {
        throw new Error(`${url} failed after ${attempt} attempt(s): ${detail}`, { cause: error });
      }
      const delay = Math.max(2000 * 2 ** (attempt - 1), Math.min(60000, retryAfter || 0));
      console.warn(`Card page ${number}, attempt ${attempt}/${maxAttempts}: ${detail}. Retrying in ${delay / 1000}s.`);
      await sleep(delay);
    }
  }
}

// Same name matching the team page uses: no accents, punctuation, or Jr./Sr. suffixes.
function normalizeName(name) {
  return String(name || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.'’]/g, "")
    .replace(/\s+(jr|sr|ii|iii|iv)$/i, "")
    .replace(/\s+/g, " ")
    .toLowerCase()
    .trim();
}

async function main() {
  const first = await page(1);
  const pages = [first];
  const queue = Array.from({ length: first.total_pages - 1 }, (_, index) => index + 2);
  await Promise.all(Array.from({ length: 2 }, async () => {
    while (queue.length) pages.push(await page(queue.shift()));
  }));

  // name → rating. Two players with the same name are stored as [[team, rating], ...].
  // names keeps the proper spelling (accents, apostrophes) that Fantrax leaves out, e.g. "Ronald Acuña Jr.".
  const ratings = {};
  const names = {};
  pages.flatMap(result => result.items)
    .filter(card => card.series === "Live")
    .forEach(card => {
      const key = normalizeName(card.name);
      const entry = [card.team_short_name, card.ovr];
      if (/[^\x00-\x7f]|'/.test(card.name)) names[key] = card.name;
      if (ratings[key] === undefined) ratings[key] = card.ovr;
      else ratings[key] = [...(Array.isArray(ratings[key]) ? ratings[key] : [[null, ratings[key]]]), entry];
    });

  const updated = new Date().toISOString().slice(0, 10);
  if (!Object.keys(ratings).length) {
    throw new Error("No Live Series ratings returned; keeping the existing ratings file.");
  }
  const js = [
    `// Generated by scripts/update-show-ratings.js from MLB The Show ${GAME_YEAR} Live Series cards. Don't edit by hand.`,
    "// Keys are normalized player names (no accents, punctuation, or Jr./Sr.).",
    `window.UTI_SHOW_RATINGS = ${JSON.stringify({ updated, game: `MLB The Show ${GAME_YEAR}`, ratings, names })};`,
    ""
  ].join("\n");
  fs.writeFileSync(OUT_FILE, js);
  console.log(`Saved ${Object.keys(ratings).length} player ratings.`);
}

async function run() {
  try {
    await main();
  } catch (error) {
    // A denied upstream request must not block the independent roster update.
    // Only skip when there is a usable snapshot; never write partial data or change its date.
    if (error.cause?.status === 403) {
      let cached;
      try {
        const source = fs.readFileSync(OUT_FILE, "utf8");
        const match = source.match(/window\.UTI_SHOW_RATINGS\s*=\s*([\s\S]*);\s*$/);
        cached = match && JSON.parse(match[1]);
      } catch {
        // Missing or corrupt data must still fail the job.
      }
      if (cached?.ratings && Object.keys(cached.ratings).length && cached.updated) {
        console.warn(`::warning::The Show API denied access (HTTP 403). Ratings were NOT refreshed; keeping the snapshot dated ${cached.updated}. Roster updates can still be committed.`);
        return;
      }
    }
    throw error;
  }
}

if (require.main === module) {
  run().catch(error => {
    console.error(error.stack || error.message);
    process.exitCode = 1;
  });
}

module.exports = { page, main, run };
