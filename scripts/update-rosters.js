/*
  Saves every UTI team's current Fantrax roster to data/rosters.js for the team pages.

  Run: node scripts/update-rosters.js
  Uses Fantrax's public API, so no login is needed.
  Each player is [slot, status, name, MLB team, position, MLB player ID]:
    slot     roster spot (C, 1B, OF, CI, MI, UT, SP, RP, P, ...)
    status   ACTIVE, RESERVE, INJURED_RESERVE, or MINORS
    position the player's main position (a P slot holds a starter when this is SP)
    MLB ID   from the MLB Stats API, used for headshots (null when not found)
*/
const fs = require("fs");
const path = require("path");

// League IDs live in scripts/fantrax-config.js (Fantrax gives the league a new ID each season).
const LEAGUE_ID = require("./fantrax-config.js").rosterLeague;
const ROOT = path.join(__dirname, "..");
const OUT_FILE = path.join(ROOT, "data/rosters.js");

async function getJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  return response.json();
}

// Team names as the rest of the site spells them (the weekly stats), so "This is Mizerable" becomes "This Is Mizerable".
function siteTeamNames() {
  const sandbox = {};
  new Function("window", fs.readFileSync(path.join(ROOT, "data/weekly-team-stats.js"), "utf8"))(sandbox);
  return [...new Set((sandbox.UTI_WEEKLY_TEAM_STATS || []).map(row => row.team))];
}

function normalizeName(name) {
  return String(name || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[.'’]/g, "")
    .replace(/-[PH]$/, "") // Fantrax lists two-way players twice: "Shohei Ohtani-P" and "Shohei Ohtani-H"
    .replace(/\s+(jr|sr|ii|iii|iv)$/i, "").replace(/\s+/g, " ").toLowerCase().trim();
}

// normalized name → MLB player ID, from MLB and the minors (this season first, then last season
// for players who missed this one, e.g. injured all year).
async function mlbPlayerIds() {
  const ids = new Map();
  const year = new Date().getFullYear();
  for (const season of [year, year - 1]) {
    for (const sport of [1, 11, 12, 13, 14, 16]) {
      const data = await getJson(`https://statsapi.mlb.com/api/v1/sports/${sport}/players?season=${season}`).catch(() => ({}));
      (data.people || []).forEach(person => {
        const key = normalizeName(person.fullName);
        if (!ids.has(key)) ids.set(key, person.id);
      });
    }
  }
  return ids;
}

// Fantrax lists names as "Last, First" (e.g. "Acuna Jr., Ronald").
function displayName(fantraxName = "") {
  const [last, first] = fantraxName.split(", ");
  return first ? `${first} ${last}` : fantraxName;
}

async function main() {
  const [rosters, players, mlbIds] = await Promise.all([
    getJson(`https://www.fantrax.com/fxea/general/getTeamRosters?leagueId=${LEAGUE_ID}`),
    getJson("https://www.fantrax.com/fxea/general/getPlayerIds?sport=MLB"),
    mlbPlayerIds()
  ]);

  const known = siteTeamNames();
  const siteName = name => known.find(team => team.toLowerCase() === String(name).toLowerCase()) || name;

  const teams = {};
  Object.values(rosters.rosters || {}).forEach(roster => {
    teams[siteName(roster.teamName)] = roster.rosterItems.map(item => {
      const player = players[item.id] || {};
      const name = displayName(player.name || item.id);
      return [item.position, item.status, name, player.team || "", player.position || item.position, mlbIds.get(normalizeName(name)) || null];
    });
  });

  const updated = new Date().toISOString().slice(0, 10);
  const js = [
    "// Generated by scripts/update-rosters.js from Fantrax. Don't edit by hand.",
    "// Each player: [slot, status, name, MLB team, position, MLB player ID].",
    // One player per line keeps the weekly diffs readable.
    "window.UTI_ROSTERS = {",
    `  "updated": ${JSON.stringify(updated)},`,
    "  \"teams\": {",
    Object.entries(teams)
      .map(([team, list]) => `    ${JSON.stringify(team)}: [\n${list.map(player => `      ${JSON.stringify(player)}`).join(",\n")}\n    ]`)
      .join(",\n"),
    "  }",
    "};",
    ""
  ].join("\n");
  fs.writeFileSync(OUT_FILE, js);
  const all = Object.values(teams).flat();
  const missing = all.filter(player => !player[5]).map(player => player[2]);
  console.log(`Saved ${Object.keys(teams).length} rosters (${all.length} players, ${all.length - missing.length} with MLB IDs).`);
  if (missing.length) console.log(`No MLB ID: ${missing.join(", ")}`);
}

main().catch(error => {
  console.error(error.message);
  process.exit(1);
});
