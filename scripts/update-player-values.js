#!/usr/bin/env node
/*
  Writes data/player-values.js: every player's dynasty value from data/players.js,
  as a plain browser script (window.UTI_PLAYER_VALUES).

  data/players.js is an ES module, which browsers won't run from a file:// page and which
  needs a module loader. The site header's title odds read this generated file instead.

  Run locally:   node scripts/update-player-values.js
  GitHub Actions runs it daily (.github/workflows/update-trending-players.yml).
*/
const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");

const ROOT_DIR = path.resolve(__dirname, "..");
const PLAYERS_PATH = path.join(ROOT_DIR, "data", "players.js");
const OUTPUT_PATH = path.join(ROOT_DIR, "data", "player-values.js");

async function main() {
  const { players, normalizeName } = await import(pathToFileURL(PLAYERS_PATH).href);

  // [normalized name, value] pairs, one per entry in players.js (some names appear more than once).
  // Names use the same normalization as players.js: letters and digits only, lowercase.
  const values = players.map(player => [normalizeName(player.name), player.dynastyValue]);

  const rows = values.map(pair => `  ${JSON.stringify(pair)}`).join(",\n");
  const output = `// Auto-generated by scripts/update-player-values.js from data/players.js. Do not edit by hand.\n` +
    `// [normalized player name, dynasty value] pairs. Names: letters and digits only, lowercase.\n\n` +
    `window.UTI_PLAYER_VALUES = [\n${rows}\n];\n`;

  fs.writeFileSync(OUTPUT_PATH, output, "utf8");
  console.log(`Wrote ${values.length} player values to data/player-values.js`);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
